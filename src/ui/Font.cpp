const uint8_t* glyphRows(char c) {
    unsigned char uc = static_cast<unsigned char>(c);
    if (uc >= 'a' && uc <= 'z') uc = static_cast<unsigned char>(uc - 'a' + 'A');
    if (uc >= 128) uc = '?';
    return table().rows[uc];
}

