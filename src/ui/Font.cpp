struct FontTable {
    uint8_t rows[128][kGlyphH];

    FontTable() {
        std::memset(rows, 0, sizeof(rows));
        for (const GlyphArt& g : kArt) {
            auto index = static_cast<unsigned char>(g.c);
            for (int y = 0; y < kGlyphH; ++y) {
                uint8_t mask = 0;
                for (int x = 0; x < kGlyphW; ++x) {
                    if (g.rows[y][x] != ' ') mask |= static_cast<uint8_t>(1u << (kGlyphW - 1 - x));
                }
                rows[index][y] = mask;
            }
        }
    }
};

const FontTable& table() {
    static FontTable t;
    return t;
}

